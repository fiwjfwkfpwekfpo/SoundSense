import standard from './styles/standard.json';
import retro from './styles/retro.json';
import flat from './styles/flat.json';
import soft from './styles/soft.json';
import compact from './styles/compact.json';
import mono from './colors/mono.json';
import amethyst from './colors/amethyst.json';
import silver from './colors/silver.json';
import lime from './colors/lime.json';
import gold from './colors/gold.json';
import amoled from './colors/amoled.json';
import highContrast from './colors/high-contrast.json';
import cover from './colors/cover.json';
import smooth from './motion/smooth.json';
import snappy from './motion/snappy.json';
import spring from './motion/spring.json';
import retroMotion from './motion/retro.json';
import minimal from './motion/minimal.json';
import off from './motion/off.json';
import { parseColorPack, parseMotionPack, parseStylePack } from './validate';
import type { ColorPack, MotionPack, StylePack } from './schema';
export const styles: Record<string, StylePack> = Object.fromEntries(Object.entries({ standard, soft, compact, flat, retro }).map(([id, data]) => [id, parseStylePack(data)]));
export const colors: Record<string, ColorPack> = Object.fromEntries(Object.entries({ cover, amethyst, silver, lime, gold, mono, amoled, 'high-contrast': highContrast }).map(([id, data]) => [id, parseColorPack(data)]));
export const motions: Record<string, MotionPack> = Object.fromEntries(Object.entries({ smooth, snappy, spring, retro: retroMotion, minimal, off }).map(([id, data]) => [id, parseMotionPack(data)]));
